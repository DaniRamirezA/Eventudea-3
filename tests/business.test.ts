test("Persistencia tras recarga, registro, login de tres perfiles y sesión local", async () => {
  const storage = new Map<string, string>();
  Object.defineProperty(globalThis, "localStorage", { configurable: true, value: { getItem: (key: string) => storage.get(key) ?? null, setItem: (key: string, value: string) => storage.set(key, value), removeItem: (key: string) => storage.delete(key) } });
  const repo = new LocalRepository();
  for (const email of ["asistente@udea.edu.co", "organizador@udea.edu.co", "admin@udea.edu.co"]) {
    const result = await authenticate(repo, email, DEMO_PASSWORD);
    assert(result.user.active);
  }
  const result = await registerUser(repo, "Estudiante Nuevo", "nuevo@udea.edu.co", DEMO_PASSWORD);
  assert.equal(result.user.role, "asistente");
  assert.notEqual(result.user.passwordHash, DEMO_PASSWORD);
  await assert.rejects(registerUser(repo, "Otra Cuenta", "NUEVO@udea.edu.co", DEMO_PASSWORD), /cuenta/);
  await assert.rejects(authenticate(repo, "nuevo@udea.edu.co", "incorrecta"), /incorrectas/);
  let data = execute(result.db, result.user.id, { type: "enroll", eventId: 1 });
  repo.save(data);
  const reloaded = await new LocalRepository().load();
  assert.deepEqual(reloaded, data);
  assert(storage.has(DATA_KEY));
  localStorage.setItem(SESSION_KEY, result.user.id);
  assert.equal(localStorage.getItem(SESSION_KEY), result.user.id);
  localStorage.removeItem(SESSION_KEY);
  assert.equal(localStorage.getItem(SESSION_KEY), null);
  data = execute(data, "d1", { type: "user", id: result.user.id, role: "asistente", active: false });
  repo.save(data);
  await assert.rejects(authenticate(repo, "nuevo@udea.edu.co", DEMO_PASSWORD), /inactiva/);
});
