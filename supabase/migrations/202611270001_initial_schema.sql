-- Create a registration safely: lock the event row before checking capacity.
create or replace function public.register_for_event(p_event_id bigint)
returns public.registrations
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_event public.events%rowtype;
  v_registration public.registrations%rowtype;
  v_count integer;
begin
  if not public.is_active_app_user() or public.current_app_role() <> 'asistente' then
    raise exception 'Solo los asistentes con cuenta activa pueden inscribirse.';
  end if;

  select * into v_event from public.events where id = p_event_id for update;
  if not found or v_event.status <> 'Publicado'
     or (v_event.event_date + v_event.event_time) <= now() then
    raise exception 'El evento no está abierto a inscripciones.';
  end if;

  if exists (
    select 1 from public.registrations
    where user_id = (select auth.uid()) and event_id = p_event_id and cancelled = false
  ) then
    raise exception 'Ya tienes una inscripción activa para este evento.';
  end if;

  select count(*) into v_count from public.registrations
  where event_id = p_event_id and cancelled = false;
  if v_count >= v_event.capacity then
    raise exception 'No hay cupos disponibles.';
  end if;

  insert into public.registrations (user_id, event_id, code)
  values (
    (select auth.uid()),
    p_event_id,
    'EVT-' || p_event_id::text || '-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 12))
  )
  returning * into v_registration;

  return v_registration;
end;
$$;

create or replace function public.cancel_registration(p_registration_id uuid)
returns public.registrations
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_registration public.registrations%rowtype;
  v_event public.events%rowtype;
begin
  select * into v_registration
  from public.registrations
  where id = p_registration_id and user_id = (select auth.uid())
  for update;

  if not found or v_registration.cancelled or v_registration.attendance_status = 'Asistió' then
    raise exception 'La inscripción no se puede cancelar.';
  end if;

  select * into v_event from public.events where id = v_registration.event_id;
  if not found or (v_event.event_date + v_event.event_time) <= now() then
    raise exception 'El evento ya comenzó o finalizó.';
  end if;

  update public.registrations set cancelled = true
  where id = p_registration_id returning * into v_registration;
  return v_registration;
end;
$$;

create or replace function public.record_event_attendance(p_code text, p_percent smallint)
returns public.registrations
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_registration public.registrations%rowtype;
  v_event public.events%rowtype;
begin
  if not public.is_active_app_user()
     or public.current_app_role() not in ('organizador', 'administrador') then
    raise exception 'No tienes permisos para registrar asistencia.';
  end if;
  if p_percent < 0 or p_percent > 100 then
    raise exception 'El porcentaje debe estar entre 0 y 100.';
  end if;

  select * into v_registration
  from public.registrations
  where code = trim(p_code) and cancelled = false
  for update;
  if not found then raise exception 'Código no válido o inscripción cancelada.'; end if;

  select * into v_event from public.events where id = v_registration.event_id;
  if not found or (v_event.status not in ('Publicado', 'Finalizado')) then
    raise exception 'El evento no está publicado.';
  end if;
  if public.current_app_role() <> 'administrador'
     and v_event.organizer_id <> (select auth.uid()) then
    raise exception 'No tienes permisos sobre este evento.';
  end if;
  if v_registration.attendance_status = 'Asistió' then
    raise exception 'Esta asistencia ya fue registrada.';
  end if;

  update public.registrations
  set attendance_status = 'Asistió',
      attendance_percent = p_percent,
      attended_at = now()
  where id = v_registration.id
  returning * into v_registration;
  return v_registration;
end;
$$;

create or replace function public.review_event(p_event_id bigint, p_approve boolean, p_observations text default '')
returns public.events
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_event public.events%rowtype;
begin
  if not public.is_app_admin() then raise exception 'Solo el administrador puede revisar eventos.'; end if;
  select * into v_event from public.events where id = p_event_id for update;
  if not found or v_event.status <> 'Pendiente de aprobación' then
    raise exception 'El evento ya no está pendiente de aprobación.';
  end if;
  if p_approve and (v_event.event_date + v_event.event_time) <= now() then
    raise exception 'No se puede publicar un evento cuya fecha ya pasó.';
  end if;
  if not p_approve and length(trim(coalesce(p_observations, ''))) < 5 then
    raise exception 'Explica el motivo del rechazo (mínimo 5 caracteres).';
  end if;
  update public.events
  set status = case when p_approve then 'Publicado' else 'Rechazado' end,
      observations = trim(coalesce(p_observations, ''))
  where id = p_event_id returning * into v_event;
  return v_event;
end;
$$;

create or replace function public.admin_update_profile(p_user_id uuid, p_role text, p_is_active boolean)
returns public.profiles
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_profile public.profiles%rowtype;
begin
  if not public.is_app_admin() then raise exception 'Solo el administrador puede gestionar usuarios.'; end if;
  if p_role not in ('asistente', 'organizador', 'administrador') then
    raise exception 'Rol inválido.';
  end if;
  if p_user_id = (select auth.uid()) and (p_role <> 'administrador' or not p_is_active) then
    raise exception 'No puedes retirar tu propio acceso administrativo.';
  end if;
  update public.profiles set role = p_role, is_active = p_is_active
  where id = p_user_id returning * into v_profile;
  if not found then raise exception 'Usuario no encontrado.'; end if;
  return v_profile;
end;
$$;

create or replace function public.finish_event(p_event_id bigint)
returns public.events
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_event public.events%rowtype;
begin
  select * into v_event from public.events where id = p_event_id for update;
  if not found then raise exception 'Evento no encontrado.'; end if;
  if public.current_app_role() <> 'administrador'
     and (public.current_app_role() <> 'organizador' or v_event.organizer_id <> (select auth.uid())) then
    raise exception 'No tienes permisos sobre este evento.';
  end if;
  if v_event.status <> 'Publicado' or (v_event.event_date + v_event.event_time) > now() then
    raise exception 'Solo se pueden finalizar eventos publicados cuya fecha y hora ya pasaron.';
  end if;
  update public.events set status = 'Finalizado'
  where id = p_event_id returning * into v_event;
  return v_event;
end;
$$;

create or replace function public.issue_certificate(p_registration_id uuid, p_template_id bigint)
returns public.certificates
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_registration public.registrations%rowtype;
  v_event public.events%rowtype;
  v_certificate public.certificates%rowtype;
begin
  select * into v_registration from public.registrations
  where id = p_registration_id and cancelled = false;
  if not found or v_registration.attendance_status <> 'Asistió' then
    raise exception 'La inscripción no cumple los requisitos de asistencia.';
  end if;
  select * into v_event from public.events where id = v_registration.event_id;
  if (v_event.event_date + v_event.event_time) > now()
     or v_registration.attendance_percent < v_event.minimum_attendance then
    raise exception 'El participante aún no cumple los requisitos del certificado.';
  end if;
  if public.current_app_role() <> 'administrador'
     and (public.current_app_role() <> 'organizador' or v_event.organizer_id <> (select auth.uid()))
     and v_registration.user_id <> (select auth.uid()) then
    raise exception 'No tienes permisos para emitir este certificado.';
  end if;
  if p_template_id is not null and not exists (
    select 1 from public.certificate_templates
    where id = p_template_id and is_active = true
  ) then
    raise exception 'La plantilla seleccionada no está activa.';
  end if;
  insert into public.certificates (registration_id, template_id, verification_code)
  values (
    p_registration_id,
    p_template_id,
    'CERT-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 16))
  )
  on conflict (registration_id) do update
    set template_id = excluded.template_id
  returning * into v_certificate;
  return v_certificate;
end;
$$;

-- Counts are derived from active registrations instead of stored redundantly.
create or replace view public.event_registration_counts
with (security_invoker = true)
as
select e.id as event_id, count(r.id)::integer as registered
from public.events e
left join public.registrations r
  on r.event_id = e.id and r.cancelled = false
group by e.id;

